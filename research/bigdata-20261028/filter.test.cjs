const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '大数据学院课程研究预览.html'), 'utf8');
const decode = s => s.replaceAll('&quot;', '"').replaceAll('&#x27;', "'").replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&amp;', '&');
const cards = [...html.matchAll(/<details class="course"([^>]+)>/g)].map(m => {
  const attrs = Object.fromEntries([...m[1].matchAll(/data-([a-z]+)="([^"]*)"/g)].map(a => [a[1], decode(a[2])]));
  return {dataset: attrs, hidden: false};
});
const elements = Object.fromEntries(['q', 'plan', 'type', 'prefix', 'count'].map(id => [id, {value: '', textContent: '', addEventListener() {}}]));
const context = vm.createContext({document: {getElementById: id => elements[id], querySelectorAll: () => cards}});
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
vm.runInContext(script, context);
const filter = () => {vm.runInContext('filter()', context); return cards.filter(c => !c.hidden);};
assert.equal(filter().length, 84);
elements.q.value = 'CS20017';
assert(filter().length >= 1);
assert(filter().every(c => c.dataset.search.includes('cs20017')));
elements.q.value = 'hzf';
assert(filter().some(c => c.dataset.search.includes('黄增峰')));
elements.q.value = '数学分析BII';
assert.equal(filter().length, 1, 'Roman numeral and ASCII title variants must match');
elements.q.value = '期末考试';
assert.equal(filter().length, 0, 'Review and syllabus text must not match course searches');
elements.q.value = '';
elements.prefix.value = 'STAT';
assert(filter().length > 0);
assert(filter().every(c => c.dataset.prefix === 'STAT'));
elements.q.value = '数据结构';
assert.equal(filter().length, 0, 'Code-prefix and text filters must intersect');
elements.q.value = ''; elements.prefix.value = '';
const professional = cards.flatMap(c => JSON.parse(c.dataset.plans)).find(p => p !== '2026级 公共方案');
assert(professional);
elements.plan.value = professional;
let selected = filter();
assert(selected.length > 0);
assert(selected.every(c => JSON.parse(c.dataset.plans).some(p => p === professional || p === '2026级 公共方案')));
for (const c of cards.filter(c => JSON.parse(c.dataset.plans).includes('2026级 公共方案'))) assert.equal(c.hidden, false, 'Public program must accompany the selected professional program');
elements.plan.value = ''; elements.type.value = '专业必修课程';
assert(filter().every(c => JSON.parse(c.dataset.types).includes('专业必修课程')));
elements.type.value = '';
assert.equal(filter().length, 84);
console.log('Course, teacher initials, excluded body text, course type, code prefix, and public + professional program filter checks passed');
